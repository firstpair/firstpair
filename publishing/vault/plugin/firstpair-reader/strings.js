function readerText(lang, key, vars = {}) {
  const language = Object.prototype.hasOwnProperty.call(STRINGS, lang) ? lang : "en";
  const template = STRINGS[language][key] ?? STRINGS.en[key];
  if (template === undefined) return uiText(language, key, vars);
  return template.replace(/\{([a-z_]+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  ));
}

module.exports = { STRINGS, readerText };
