#!/usr/bin/env python3
"""Build the mobile-safe single-file FirstPair Triptych runtime.

Obsidian release/install assets load one compiled ``main.js``. The authored
runtime stays readable in ``main-source.js`` and ``review-state.js``; this
small standard-library bundler embeds the pure state module without leaving a
relative ``require()`` for the iOS loader to resolve.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
PLUGIN = ROOT / "publishing" / "vault" / "plugin" / "firstpair-triptych"
ENTRY = PLUGIN / "main-source.js"
STATE = PLUGIN / "review-state.js"
OUTPUT = PLUGIN / "main.js"
REQUIRE = 'require("./review-state")'


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def indent(text: str, spaces: int = 2) -> str:
    prefix = " " * spaces
    return "\n".join(f"{prefix}{line}" if line else "" for line in text.splitlines())


def bundled_source() -> str:
    entry_source = ENTRY.read_text(encoding="utf-8")
    state_source = STATE.read_text(encoding="utf-8")
    if entry_source.count(REQUIRE) != 1:
        raise RuntimeError(f"expected exactly one {REQUIRE!r} in {ENTRY}")
    bundled_entry = entry_source.replace(REQUIRE, "__firstpairReviewState")
    return (
        '"use strict";\n\n'
        "/* Generated by publishing/scripts/bundle-firstpair-triptych.py.\n"
        f" * main-source-sha256: {sha256(entry_source)}\n"
        f" * review-state-sha256: {sha256(state_source)}\n"
        " * Do not edit this release asset directly.\n"
        " */\n"
        "const __firstpairReviewState = (() => {\n"
        "  const module = { exports: {} };\n"
        "  const exports = module.exports;\n"
        "  ((module, exports) => {\n"
        f"{indent(state_source, 4)}\n"
        "  })(module, exports);\n"
        "  return module.exports;\n"
        "})();\n\n"
        f"{bundled_entry.rstrip()}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when main.js is not the current deterministic bundle",
    )
    args = parser.parse_args()
    expected = bundled_source()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
    if args.check:
        if current != expected:
            raise SystemExit(f"stale FirstPair Triptych bundle: {OUTPUT}")
        return 0
    if current != expected:
        OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
