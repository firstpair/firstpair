#!/usr/bin/env python3
"""Bundle a FirstPair Obsidian plugin into one mobile-safe ``main.js``.

Obsidian loads a single ``main.js``; on iOS a relative ``require()`` cannot be
resolved, so every relative module the entry point reaches (``./x`` or
``../other-plugin/x``) is embedded once in a small module table.  ``obsidian``
and Node built-ins pass through to the host ``require`` (the built-ins are
only ever required lazily on desktop code paths).

    python3 publishing/scripts/bundle-obsidian-plugin.py <plugin dir> [--check]

The output is deterministic: modules are ordered by first reach and the
header records the SHA-256 of every embedded source.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

REQUIRE_RE = re.compile(r"""require\((["'])(\.{1,2}/[^"']+)\1\)""")
# styles-source.css may import shared stylesheets; Obsidian loads one styles.css.
IMPORT_RE = re.compile(r"""^@import\s+["'](\.{1,2}/[^"']+\.css)["'];\s*$""", re.M)


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def resolve(base: Path, spec: str) -> Path:
    target = (base.parent / spec).resolve()
    if target.suffix != ".js":
        target = target.with_suffix(".js")
    if not target.is_file():
        raise FileNotFoundError(f"{spec} required from {base} does not exist ({target})")
    return target


def collect(entry: Path) -> list[Path]:
    order: list[Path] = []
    stack = [entry.resolve()]
    seen: set[Path] = set()
    while stack:
        path = stack.pop(0)
        if path in seen:
            continue
        seen.add(path)
        order.append(path)
        for match in REQUIRE_RE.finditer(path.read_text(encoding="utf-8")):
            stack.append(resolve(path, match.group(2)))
    return order


def bundled_source(plugin: Path) -> str:
    entry = plugin / "main-source.js"
    modules = collect(entry)
    root = plugin.resolve().parent
    ids = {path: path.relative_to(root).as_posix() for path in modules}
    header = [
        '"use strict";',
        "",
        "/* Generated by publishing/scripts/bundle-obsidian-plugin.py.",
        *[f" * {ids[path]}: sha256 {sha256(path.read_text(encoding='utf-8'))}" for path in modules],
        " * Do not edit this release asset directly.",
        " */",
        "const __firstpairModules = {};",
        "const __firstpairCache = {};",
        "function __firstpairRequire(id) {",
        "  if (Object.prototype.hasOwnProperty.call(__firstpairCache, id)) return __firstpairCache[id].exports;",
        "  const module = { exports: {} };",
        "  __firstpairCache[id] = module;",
        "  __firstpairModules[id](module, module.exports);",
        "  return module.exports;",
        "}",
    ]
    body: list[str] = []
    for path in modules[1:]:
        source = path.read_text(encoding="utf-8")
        source = REQUIRE_RE.sub(
            lambda m: f"__firstpairRequire({json.dumps(ids[resolve(path, m.group(2))])})", source,
        )
        indented = "\n".join(f"  {line}" if line else "" for line in source.splitlines())
        body.append(f"__firstpairModules[{json.dumps(ids[path])}] = (module, exports) => {{\n{indented}\n}};")
    entry_source = entry.read_text(encoding="utf-8")
    entry_source = REQUIRE_RE.sub(
        lambda m: f"__firstpairRequire({json.dumps(ids[resolve(entry, m.group(2))])})", entry_source,
    )
    return "\n".join(header) + "\n\n" + "\n\n".join(body) + ("\n\n" if body else "") + entry_source.rstrip() + "\n"


def bundled_styles(plugin: Path) -> str | None:
    source = plugin / "styles-source.css"
    if not source.is_file():
        return None
    text = source.read_text(encoding="utf-8")

    def expand(match: re.Match[str]) -> str:
        target = (source.parent / match.group(1)).resolve()
        if not target.is_file():
            raise FileNotFoundError(f"{match.group(1)} imported by {source} does not exist")
        body = target.read_text(encoding="utf-8").rstrip()
        rel = target.relative_to(plugin.resolve().parent).as_posix()
        return f"/* ---- {rel} (sha256 {sha256(body)}) ---- */\n{body}\n/* ---- end {rel} ---- */"

    header = "/* Generated by publishing/scripts/bundle-obsidian-plugin.py from styles-source.css. */\n"
    return header + IMPORT_RE.sub(expand, text).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("plugin", type=Path)
    parser.add_argument("--check", action="store_true", help="fail when main.js is stale")
    args = parser.parse_args()
    outputs = [(args.plugin / "main.js", bundled_source(args.plugin))]
    styles = bundled_styles(args.plugin)
    if styles is not None:
        outputs.append((args.plugin / "styles.css", styles))
    for output, expected in outputs:
        current = output.read_text(encoding="utf-8") if output.is_file() else None
        if args.check:
            if current != expected:
                raise SystemExit(f"stale bundle: {output}")
            continue
        if current != expected:
            output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
